#!/usr/bin/env node
// Regenerates src/engine/joker-names.js: Balatro joker key → Balatrolator joker name.
// Usage: node scripts/gen-joker-names.js <path to Balatro game.lua>
// (game.lua comes from Balatro.exe, which is a zip: `unzip Balatro.exe game.lua`.)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const gameLua = process.argv[2];
if (!gameLua) { console.error('usage: node scripts/gen-joker-names.js <game.lua>'); process.exit(1); }

const lua = readFileSync(gameLua, 'utf8');
const data = readFileSync(path.join(root, 'vendor/balatrolator/data.ts'), 'utf8').replace(/\r\n/g, '\n');
const defs = data.slice(data.indexOf('export const JOKER_DEFINITIONS'));

// Keys of JOKER_DEFINITIONS: 'Name', 'Driver\'s License' or "Name".
const keyRe = /\n\t(?:'((?:[^'\\]|\\.)+)'|"((?:[^"\\]|\\.)+)"): \{/g;
const balNames = [...defs.matchAll(keyRe)].map((m) => (m[1] ?? m[2]).replace(/\\(.)/g, '$1'));
const norm = (s) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]/g, '');
const balByNorm = new Map(balNames.map((n) => [norm(n), n]));
// Balatrolator spellings that differ from the game's.
const overrides = { caino: 'Canio', troubadour: 'Troubador', seance: 'Séance' };

const entryRe = /^\s*(j_[a-z_0-9]+)\s*=\s*\{[^\n]*?name\s*=\s*(?:"([^"]+)"|'([^']+)')/gm;
const out = {};
const missing = [];
let m;
while ((m = entryRe.exec(lua))) {
  const key = m[1];
  const gameName = m[2] ?? m[3];
  const n = norm(gameName);
  const bal = balByNorm.get(n) ?? balByNorm.get(norm(overrides[n] ?? ''));
  if (bal) out[key] = bal; else missing.push(`${key}=${gameName}`);
}

const header = '// Generated by scripts/gen-joker-names.js from Balatro game.lua P_CENTERS: joker key → Balatrolator joker\n'
  + '// name (the in-game name except Canio, Troubador and Séance, spelled as Balatrolator spells them). Do not edit by hand.\n';
const body = JSON.stringify(out, null, 2).replace(/"([a-z_0-9]+)":/g, '$1:');
writeFileSync(path.join(root, 'src/engine/joker-names.js'), `${header}export const JOKER_NAME_BY_KEY = ${body};\n`);
console.log(`mapped ${Object.keys(out).length} jokers; Balatrolator defines ${balNames.length}; unmapped: ${missing.join(', ') || 'none'}`);
